#!/usr/bin/env python3
"""Simple SPARQL versions of the three app queries, run against the dev slice
with Oxigraph (pyoxigraph). One plant each. Pure SPARQL - no DuckDB.

Every query + its actual answer is written to
plant_data/rdf/queries/SIMPLE.md

python3 run_simple_queries.py
"""

import os
import time

import pyoxigraph

NT = "plant_data/rdf/slice.nt"
OUT = "plant_data/rdf/queries/SIMPLE.md"

# The simple queries: plain triple patterns, the plant name written straight
# into the pattern, no property paths, no VALUES, no label joins.
QUERIES = [
    (
        "A - all facts for one plant: Crassula helmsii",
        """\
PREFIX dwc: <http://rs.tdwg.org/dwc/terms/>
SELECT ?predicate ?value WHERE {
  ?plant dwc:scientificName "Crassula helmsii" .
  ?plant ?predicate ?value .
  FILTER (?predicate != <http://www.w3.org/1999/02/22-rdf-syntax-ns#type>)
}
ORDER BY ?predicate ?value""",
        ["predicate", "value"],
    ),
    (
        "B - prevalence map for one plant: Heracleum mantegazzianum",
        """\
PREFIX schema:  <https://schema.org/>
PREFIX dwc:     <http://rs.tdwg.org/dwc/terms/>
PREFIX plantdb: <https://plantdb.example.org/def/>
SELECT ?areaName ?occurrences ?score WHERE {
  ?plant dwc:scientificName "Heracleum mantegazzianum" .
  ?fact plantdb:aboutPlant ?plant ;
        plantdb:observedIn ?area ;
        plantdb:occurrences ?occurrences ;
        plantdb:prevalenceScore ?score .
  ?area schema:name ?areaName .
}
ORDER BY DESC(?score) ?areaName""",
        ["areaName", "occurrences", "score"],
    ),
    (
        "C - Dutch books mentioning one plant: Quercus robur",
        """\
PREFIX schema:  <https://schema.org/>
PREFIX dwc:     <http://rs.tdwg.org/dwc/terms/>
PREFIX plantdb: <https://plantdb.example.org/def/>
SELECT ?pages ?title ?bhlUrl WHERE {
  ?plant dwc:scientificName "Quercus robur" .
  ?mention plantdb:aboutPlant ?plant ;
           plantdb:mentionsBook ?book ;
           plantdb:pages ?pages .
  ?book schema:name ?title ;
        plantdb:dutchRelevance true .
  OPTIONAL { ?book schema:url ?bhlUrl }
}
ORDER BY DESC(?pages) ?title""",
        ["pages", "title", "bhlUrl"],
    ),
    (
        "C2 - all books mentioning one plant: Quercus robur (drop the Dutch line)",
        """\
PREFIX schema:  <https://schema.org/>
PREFIX dwc:     <http://rs.tdwg.org/dwc/terms/>
PREFIX plantdb: <https://plantdb.example.org/def/>
SELECT ?pages ?title ?bhlUrl WHERE {
  ?plant dwc:scientificName "Quercus robur" .
  ?mention plantdb:aboutPlant ?plant ;
           plantdb:mentionsBook ?book ;
           plantdb:pages ?pages .
  ?book schema:name ?title .
  OPTIONAL { ?book schema:url ?bhlUrl }
}
ORDER BY DESC(?pages) ?title""",
        ["pages", "title", "bhlUrl"],
    ),
    (
        "Did-you-mean for the fragment: helmsii",
        """\
PREFIX dwc: <http://rs.tdwg.org/dwc/terms/>
SELECT ?plant ?name WHERE {
  ?plant dwc:scientificName ?name .
  FILTER (CONTAINS(lcase(str(?name)), "helmsii"))
}
LIMIT 200""",
        ["plant", "name"],
    ),
]

# expected row counts, from plant_data/rdf/queries/EXAMPLES.md
EXPECTED = {0: 45, 1: 355, 2: 34, 3: 2302}
# how many result rows go into the markdown (rest replaced by a ... row)
SHOW = {0: None, 1: 15, 2: None, 3: 15, 4: None}


def bind(sol, var):
    """Binding of ?var, or None when an OPTIONAL left it unbound."""
    try:
        return sol[var]
    except KeyError:
        return None


def cell(term):
    """One SPARQL result term -> plain markdown cell text."""
    if term is None:
        return ""
    if isinstance(term, pyoxigraph.Literal):
        v = term.value
    elif isinstance(term, pyoxigraph.NamedNode):
        v = str(term)
    else:
        v = str(term)
    return v.replace("|", "\\|").replace("\n", " ")


def main():
    t0 = time.time()
    store = pyoxigraph.Store()
    with open(NT, "rb") as fh:
        store.load(fh, format=pyoxigraph.RdfFormat.N_TRIPLES)
    print(f"loaded {NT}: {len(store):,} triples in {time.time() - t0:.1f} s")

    lines = [
        "# Simple SPARQL queries, run on the dev slice",
        "",
        f"Plain SPARQL 1.1, run with Oxigraph (pyoxigraph) over",
        f"`plant_data/rdf/slice.nt` ({len(store):,} triples). One plant per",
        "query. No DuckDB, no vendor extensions. Answers below are actual",
        "query output, generated by `python3 run_simple_queries.py`.",
        "",
    ]
    failures = 0
    for i, (title, sparql, cols) in enumerate(QUERIES):
        t0 = time.time()
        rows = [[bind(sol, c) for c in cols] for sol in store.query(sparql)]
        secs = time.time() - t0
        check = ""
        if i in EXPECTED:
            ok = len(rows) == EXPECTED[i]
            failures += 0 if ok else 1
            check = f" ({len(rows)} rows, expected {EXPECTED[i]}: " \
                    f"{'OK' if ok else 'MISMATCH'})"
        print(f"  {title.split(' - ')[0]}: {len(rows):,} rows in "
              f"{secs * 1000:.0f} ms{check}")

        lines += [f"## {title}", "", "```sparql", sparql, "```", "",
                  f"**{len(rows):,} rows** in {secs * 1000:.0f} ms"
                  + (f", expected {EXPECTED[i]} - {'OK' if len(rows) == EXPECTED[i] else 'MISMATCH'}"
                     if i in EXPECTED else ""), ""]
        limit = SHOW[i]
        shown = rows if limit is None or len(rows) <= limit else rows[:limit]
        lines.append("| " + " | ".join(cols) + " |")
        lines.append("|" + "---|" * len(cols))
        for r in shown:
            lines.append("| " + " | ".join(cell(t) for t in r) + " |")
        if len(rows) > len(shown):
            lines.append("| ... | | |")
        lines.append("")

    lines += [
        "## Notes",
        "",
        "- Row counts match the full-file expectations in `EXAMPLES.md`",
        "  (45 / 355 / 34 / 2,302) because every fact of a slice plant is",
        "  exported in full - the slice cuts whole plants out, never rows",
        "  of a plant that stays.",
        "- Query A returns the raw value: `plantdb:nlStatus` comes back as",
        "  the status URI (`.../status/invasive`), where the original A.rq",
        "  resolves its English label ('Invasive in NL') via an OPTIONAL",
        "  label join. If the app wants labels, that one join is worth",
        "  adding back; everything else the simplification drops was",
        "  lookup machinery, not answer content.",
        "- Gotcha found while running: the shipped `A.rq` declares",
        "  `PREFIX rdf: <http://www.w3.org/1999-02-22-rdf-syntax-ns#>` -",
        "  dashes where the real RDF namespace has slashes",
        "  (`.../1999/02/22-rdf-syntax-ns#`). The `.nt` files use the",
        "  correct namespace. Oxigraph happens to still filter types out,",
        "  but the same filter shape leaks the two rdf:type rows in a",
        "  simpler query - other engines may differ. Query A above spells",
        "  the full IRI inline, which works everywhere.",
        "- Did-you-mean is narrower than the shipped version: it searches",
        "  `dwc:scientificName` only (not synonyms/normalised names), over",
        "  the 200-plant slice - so 1 hit, where the shipped query on the",
        "  full export gives 44.",
        "",
    ]

    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
